"""Verify the homepage tree and diagram against generated Parcel sources and graph."""

import argparse
import re
import socket
import sys
import tempfile
from html.parser import HTMLParser
from itertools import pairwise
from pathlib import Path


class Illustration(HTMLParser):
    def __init__(self):
        super().__init__()
        self.tree = []
        self.in_tree = False
        self.nodes = {}
        self.edges = set()

    def handle_starttag(self, tag, attrs):
        attrs = {key: value for key, value in attrs if value is not None}
        if tag == "pre" and attrs.get("class") == "project-overview-tree":
            self.in_tree = True
        if "data-project-node" in attrs:
            self.nodes[attrs["data-project-node"]] = attrs["data-logical-id"]
        if "data-project-edge" in attrs:
            self.edges.add(tuple(attrs["data-project-edge"].split("|")))

    def handle_endtag(self, tag):
        if tag == "pre":
            self.in_tree = False

    def handle_data(self, data):
        if self.in_tree:
            self.tree.append(data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--weaver-checkout", required=True, type=Path)
    args = parser.parse_args()
    source = args.weaver_checkout.resolve()
    sys.path[:0] = [
        str(source / "src"),
        str(source / "tests"),
        str(source / "tests/targeted"),
    ]
    import weaver
    from check_docs_refresh_examples import parse, refuse_network
    from factories import installed_catalogue, item_bindings
    from named_journey_support import OfflineInitialiser
    from weaver.declaration.model import WeaverItemId
    from weaver.load_plan import LoadDag

    assert Path(weaver.__file__).resolve().is_relative_to(source / "src")
    socket.socket.connect = refuse_network
    socket.create_connection = refuse_network
    page = Path(__file__).resolve().parents[1] / "docs/index.md"
    html = Illustration()
    html.feed(page.read_text())
    lines = "".join(html.tree).strip().splitlines()
    assert 12 <= len(lines) <= 18, "Homepage needs one compact project tree"
    assert lines[0] == "parcel/"
    assert len(html.nodes) == 5 and len(html.edges) == 4
    with (
        tempfile.TemporaryDirectory(prefix="homepage-parcel-") as temp,
        OfflineInitialiser() as initialise,
    ):
        root = Path(temp)
        initialise(
            root,
            catalogue="Catalogue",
            environment="Weaver",
            lakehouse="Landing",
            warehouse="Operations",
            semantic_model="Parcel",
        )
        parents = [root]
        for line in lines[1:]:
            match = re.fullmatch(r"((?:│   |    )*)(?:├── |└── )(.+)", line)
            assert match, line
            depth = len(match[1]) // 4
            path = parents[depth] / match[2]
            assert path.exists(), f"Not generated by Parcel: {path.relative_to(root)}"
            if match[2].endswith("/"):
                assert path.is_dir()
                parents[depth + 1 :] = [path]
        repository = parse(root)
        catalogue = installed_catalogue(
            repository,
            item_bindings(
                ("Lakehouse/Landing", "Landing"), ("Warehouse/Operations", "Operations")
            ),
        )
        graph = catalogue.dag()
        selected = set(html.nodes.values())
        assert selected <= {str(node.identity) for node in graph.nodes}
        actual = set()
        for edge in graph.edges:
            chain = (
                [edge.upstream, edge.through, edge.downstream]
                if edge.through
                else [edge.upstream, edge.downstream]
            )
            actual.update(
                (str(a), str(b))
                for a, b in pairwise(chain)
                if str(a) in selected and str(b) in selected
            )
        drawn = {(html.nodes[a], html.nodes[b]) for a, b in html.edges}
        assert drawn == actual, {"drawn": sorted(drawn), "actual": sorted(actual)}
        plan = LoadDag.from_catalogue(
            catalogue,
            items=[
                WeaverItemId.parse("Lakehouse/Landing"),
                WeaverItemId.parse("Warehouse/Operations"),
            ],
        )
        order = [str(node.logical_id) for node in plan.order() if node.logical_id]
        for a, b in actual:
            if a in order and b in order:
                assert order.index(a) < order.index(b)
        print(
            f"PASS: {len(lines)} tree lines, {len(selected)} logical nodes, {len(actual)} exact dependency edges; production LoadDag ordering verified offline"
        )
        for upstream, downstream in sorted(actual):
            print(f"  {upstream} -> {downstream}")


if __name__ == "__main__":
    main()
